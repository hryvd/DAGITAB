BEGIN;

-- Serialize with Vercel's first-use initialization.
SELECT pg_advisory_xact_lock(20261118, 1);

CREATE SCHEMA IF NOT EXISTS dagitab;
REVOKE ALL ON SCHEMA dagitab FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS dagitab.teams (
  id text PRIMARY KEY,
  open integer NOT NULL DEFAULT 1 CHECK (open IN (0, 1)),
  capacity integer CHECK (capacity >= 0)
);

CREATE TABLE IF NOT EXISTS dagitab.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password text NOT NULL,
  school text NOT NULL DEFAULT '',
  teamid text REFERENCES dagitab.teams (id),
  expertise text NOT NULL DEFAULT '[]',
  intent text NOT NULL DEFAULT '',
  role text NOT NULL CHECK (role IN ('member', 'admin')),
  createdat bigint NOT NULL,
  username text,
  localdemo integer NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique
  ON dagitab.users (lower(username)) WHERE username IS NOT NULL;

CREATE TABLE IF NOT EXISTS dagitab.sessions (
  tokenhash text PRIMARY KEY,
  csrf text NOT NULL,
  userid integer REFERENCES dagitab.users (id) ON DELETE CASCADE,
  expiresat bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expiry ON dagitab.sessions (expiresat);

CREATE TABLE IF NOT EXISTS dagitab.projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL,
  teamid text NOT NULL REFERENCES dagitab.teams (id),
  status text NOT NULL CHECK (status IN ('planned', 'active', 'done'))
);

CREATE TABLE IF NOT EXISTS dagitab.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectid integer NOT NULL REFERENCES dagitab.projects (id),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  teamid text NOT NULL REFERENCES dagitab.teams (id),
  assigneeid integer REFERENCES dagitab.users (id),
  status text NOT NULL CHECK (status IN ('todo', 'in_progress', 'done')),
  createdby integer NOT NULL REFERENCES dagitab.users (id)
);

CREATE TABLE IF NOT EXISTS dagitab.rate_limits (
  key text PRIMARY KEY,
  attempts integer NOT NULL,
  expiresat timestamptz NOT NULL
);

