-- A registration and an administrator changing capacity serialize on the team row.
CREATE OR REPLACE FUNCTION dagitab.check_registration_capacity()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, dagitab AS $$
DECLARE
  team dagitab.teams%ROWTYPE;
BEGIN
  SELECT * INTO team FROM dagitab.teams WHERE id = NEW.teamid FOR UPDATE;
  IF team.open = 0 OR (
    team.capacity IS NOT NULL AND team.capacity <= (
      SELECT count(*) FROM dagitab.users WHERE teamid = NEW.teamid AND role = 'member'
    )
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'dagitab_team_closed';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS check_registration_capacity ON dagitab.users;
CREATE TRIGGER check_registration_capacity BEFORE INSERT ON dagitab.users
FOR EACH ROW WHEN (NEW.role = 'member')
EXECUTE FUNCTION dagitab.check_registration_capacity();

CREATE OR REPLACE FUNCTION dagitab.check_team_capacity()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, dagitab AS $$
BEGIN
  IF NEW.capacity < (
    SELECT count(*) FROM dagitab.users WHERE teamid = NEW.id AND role = 'member'
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'dagitab_team_capacity';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS check_team_capacity ON dagitab.teams;
CREATE TRIGGER check_team_capacity BEFORE UPDATE OF capacity ON dagitab.teams
FOR EACH ROW EXECUTE FUNCTION dagitab.check_team_capacity();

REVOKE ALL ON ALL TABLES IN SCHEMA dagitab FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA dagitab FROM PUBLIC, anon, authenticated;

COMMIT;
